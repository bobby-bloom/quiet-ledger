/// Budget row state, mapped to bar colours on track → primary,
/// ≥ threshold → warningFill, over → error.
enum BudgetState { onTrack, warning, over }

/// Parses `categories.rollover_override`; null/unknown = use the default.
RolloverMode? parseRolloverMode(String? s) =>
    s == null ? null : RolloverMode.values.asNameMap()[s];

/// Amount carried into the next period for a category whose period ended
/// with [availableMinor] = budget + rollover − spent left (negative when
/// overspent).
int rolloverFor(RolloverMode mode, int availableMinor) => switch (mode) {
  RolloverMode.none => 0,
  RolloverMode.leftover => availableMinor > 0 ? availableMinor : 0,
  RolloverMode.overspent => availableMinor < 0 ? availableMinor : 0,
  RolloverMode.both => availableMinor,
};

/// Classifies spending against an available amount with a warning
/// threshold in percent.
BudgetState budgetState({
  required int availableMinor,
  required int spentMinor,
  required int thresholdPercent,
}) {
  if (spentMinor > availableMinor) {
    return spentMinor > 0 || availableMinor < 0
        ? BudgetState.over
        : BudgetState.onTrack;
  }
  if (availableMinor <= 0) return BudgetState.onTrack;
  // spent / available >= threshold / 100, in integers.
  if (spentMinor * 100 >= availableMinor * thresholdPercent) {
    return BudgetState.warning;
  }
  return BudgetState.onTrack;
}

/// Zero-based budgeting: money still to assign in a period.
int toBeBudgeted({
  required int incomeMinor,
  required int carryMinor,
  required int assignedMinor,
}) => incomeMinor + carryMinor - assignedMinor;

/// Average of [values] over [periods] (missing periods count as 0), rounded
/// half up to cents and then up to a multiple of [roundUpTo] minor units
/// (100 = whole euros; 1 = no extra rounding).
int averageAmount(List<int> values, int periods, {int roundUpTo = 100}) {
  if (periods <= 0) return 0;
  final sum = values.fold(0, (a, b) => a + b);
  if (sum <= 0) return 0;
  final avg = (sum * 2 + periods) ~/ (periods * 2);
  if (roundUpTo <= 1) return avg;
  return ((avg + roundUpTo - 1) ~/ roundUpTo) * roundUpTo;
}

/// One budgeted category in a period.
@immutable
class BudgetLine {
  const BudgetLine({
    required this.categoryId,
    required this.name,
    required this.budgetedMinor,
    required this.rolloverMinor,
    required this.spentMinor,
    required this.thresholdPercent,
    required this.rolloverMode,
    this.parentId,
    this.icon,
    this.color,
    this.budgetId,
    this.isRoot = true,
    this.plannedMinor = 0,
    this.rule,
    this.generated = false,
    this.window,
    this.cadence,
  });

  final String categoryId;
  final String? parentId;
  final String name;
  final String? icon;
  final int? color;

  /// Id of the `budgets` row (null for a category without a budget).
  final String? budgetId;

  /// Amount set for this period.
  final int budgetedMinor;

  /// Carried in from the previous period (negative = overspent carried).
  final int rolloverMinor;

  /// Net spending in the period (parent categories include children;
  /// refunds reduce it).
  final int spentMinor;

  /// Net outstanding spending in the period (planned entries and unposted
  /// recurring occurrences; positive = still to be spent). Never part of
  /// [spentMinor], [state] or the rollover.
  final int plannedMinor;
  final int thresholdPercent;
  final RolloverMode rolloverMode;

  /// False when the parent category has its own budget (then this line is a
  /// sub-allocation and not counted in totals).
  final bool isRoot;

  /// The repeating budget covering this period, if any.
  final BudgetRulePlan? rule;

  /// The row was generated by [rule] and not edited since (an edited row is
  /// an override for this period).
  final bool generated;

  bool get repeats => rule != null;

  /// Set for a budget with its own length: the window shown (the one
  /// containing the board period's reference day). Spent, planned and the
  /// state are measured over it; it is not part of the board's totals.
  final DateRange? window;

  /// Length of [window] (week, month, quarter or year).
  final BudgetCadence? cadence;

  bool get windowed => window != null;

  int get availableMinor => budgetedMinor + rolloverMinor;
  int get remainingMinor => availableMinor - spentMinor;
  int get overMinor => remainingMinor < 0 ? -remainingMinor : 0;

  /// Spent / available (0..∞); 1 when nothing is available but something
  /// was spent.
  double get ratio {
    if (availableMinor <= 0) return spentMinor > 0 ? 1 : 0;
    return spentMinor / availableMinor;
  }

  /// Rounded percent used.
  int get percentUsed =>
      availableMinor <= 0 ? (spentMinor > 0 ? 100 : 0) : (ratio * 100).round();

  BudgetState get state => budgetState(
    availableMinor: availableMinor,
    spentMinor: spentMinor,
    thresholdPercent: thresholdPercent,
  );

  /// Spent plus outstanding.
  int get projectedSpentMinor => spentMinor + plannedMinor;
  int get projectedRemainingMinor => availableMinor - projectedSpentMinor;
  int get projectedOverMinor =>
      projectedRemainingMinor < 0 ? -projectedRemainingMinor : 0;

  /// Projected spent / available, like [ratio].
  double get projectedRatio {
    if (availableMinor <= 0) return projectedSpentMinor > 0 ? 1 : 0;
    return projectedSpentMinor / availableMinor;
  }

  /// State once everything outstanding is booked (in-app hint only; alerts
  /// use [state]).
  BudgetState get projectedState => budgetState(
    availableMinor: availableMinor,
    spentMinor: projectedSpentMinor,
    thresholdPercent: thresholdPercent,
  );

  /// Outstanding spending would take this budget over while it is not over
  /// yet.
  bool get plannedPushesOver =>
      plannedMinor > 0 &&
      state != BudgetState.over &&
      projectedState == BudgetState.over;

  /// Rollover into the next period if the period ended now.
  int get nextRolloverMinor => rolloverFor(rolloverMode, remainingMinor);

  @override
  bool operator ==(Object other) =>
      other is BudgetLine &&
      other.categoryId == categoryId &&
      other.budgetId == budgetId &&
      other.budgetedMinor == budgetedMinor &&
      other.rolloverMinor == rolloverMinor &&
      other.spentMinor == spentMinor &&
      other.plannedMinor == plannedMinor &&
      other.thresholdPercent == thresholdPercent &&
      other.rolloverMode == rolloverMode &&
      other.isRoot == isRoot &&
      other.rule == rule &&
      other.generated == generated &&
      other.window == window &&
      other.cadence == cadence &&
      other.name == name;

  @override
  int get hashCode => Object.hash(
    categoryId,
    budgetId,
    budgetedMinor,
    rolloverMinor,
    spentMinor,
    plannedMinor,
    thresholdPercent,
    rolloverMode,
    isRoot,
    rule,
    generated,
    window,
    cadence,
    name,
  );
}

/// Budgets of one period: totals and per-category lines. Exposed for the
/// dashboard as `budgetSummaryProvider`.
@immutable
class BudgetSummary {
  const BudgetSummary({
    required this.period,
    required this.today,
    required this.mode,
    required this.lines,
    this.incomeMinor = 0,
    this.carryMinor = 0,
    this.unbudgetedSpentMinor = 0,
    this.plannedIncomeMinor = 0,
    this.windowAssignedMinor = 0,
  });

  final DateRange period;
  final DateTime today;
  final BudgetMode mode;

  /// Sorted: over first, then warning, then on track; by name within.
  final List<BudgetLine> lines;

  /// Income of the period (envelope mode).
  final int incomeMinor;

  /// Unassigned money carried from the previous period (envelope mode).
  final int carryMinor;

  /// Expense spending in categories without a budget.
  final int unbudgetedSpentMinor;

  /// Expected income still outstanding (shown next to "left to assign",
  /// never added to it).
  final int plannedIncomeMinor;

  /// Envelope mode: the shares of budgets with their own length assigned
  /// to this period (spread evenly over the periods a window covers).
  final int windowAssignedMinor;

  /// Root lines of the budget period; lines with their own length have
  /// their own window and stay out of the totals.
  Iterable<BudgetLine> get _roots =>
      lines.where((l) => l.isRoot && !l.windowed);

  bool get hasWindowed => lines.any((l) => l.windowed);

  /// Budget + rollover over root lines.
  int get totalBudgetedMinor => _roots.fold(0, (a, l) => a + l.availableMinor);

  /// Amounts assigned this period (without rollovers) over root lines, plus
  /// the shares of budgets with their own length.
  int get assignedMinor =>
      _roots.fold(0, (a, l) => a + l.budgetedMinor) + windowAssignedMinor;
  int get totalSpentMinor => _roots.fold(0, (a, l) => a + l.spentMinor);
  int get totalRemainingMinor => totalBudgetedMinor - totalSpentMinor;

  /// Outstanding spending over root lines.
  int get totalPlannedMinor => _roots.fold(0, (a, l) => a + l.plannedMinor);

  /// What is left once everything outstanding is booked.
  int get projectedRemainingMinor => totalRemainingMinor - totalPlannedMinor;

  /// Envelope mode: income + carry − assigned ("€X left to assign").
  int get toBeBudgetedMinor => toBeBudgeted(
    incomeMinor: incomeMinor,
    carryMinor: carryMinor,
    assignedMinor: assignedMinor,
  );

  bool get isEmpty => lines.isEmpty;
  bool get isCurrent => period.contains(today);

  /// Today's position in the period (0..1) for the bar tick; null outside.
  double? get todayTick => isCurrent ? period.progressAt(today) : null;

  /// The bar tick of [line]: today's position in its window, or in the
  /// period.
  double? tickFor(BudgetLine line) {
    final w = line.window;
    if (w == null) return todayTick;
    return w.contains(today) ? w.progressAt(today) : null;
  }

  /// 1-based day of the period for "Today, day 23 of 31".
  int get dayOfPeriod =>
      DateTime.utc(today.year, today.month, today.day)
          .difference(
            DateTime.utc(
              period.start.year,
              period.start.month,
              period.start.day,
            ),
          )
          .inDays +
      1;

  int get daysLeft => isCurrent ? period.days - dayOfPeriod + 1 : 0;

  int count(BudgetState s) => lines.where((l) => l.state == s).length;

  BudgetLine? lineFor(String categoryId) {
    for (final l in lines) {
      if (l.categoryId == categoryId) return l;
    }
    return null;
  }
}

/// Envelope mode: money assigned to [period]. Budgets of the period count
/// for root categories; a budget with its own length counts with its share
/// of the period ([windowShare]) for a category without a budget of the
/// period. A category is not a root when its parent has a budget of either
/// kind. Rows of categories missing from [categories] are ignored. The
/// board and the carry along the chain both use this.
({int periodMinor, int windowMinor}) assignedInPeriod({
  required BudgetPeriods periods,
  required DateRange period,
  required Iterable<Budget> periodRows,
  required Iterable<Budget> windowRows,
  required Map<String, Category> categories,
}) {
  final budgeted = {
    for (final r in periodRows)
      if (categories.containsKey(r.categoryId)) r.categoryId,
  };
  final windows = dropNestedWindows(windowRows.toList());
  final windowed = {
    for (final r in windows)
      if (categories.containsKey(r.categoryId) &&
          !budgeted.contains(r.categoryId))
        r.categoryId,
  };
  bool root(String id) {
    final parent = categories[id]?.parentId;
    return parent == null ||
        (!budgeted.contains(parent) && !windowed.contains(parent));
  }

  var periodMinor = 0;
  for (final r in periodRows) {
    if (budgeted.contains(r.categoryId) && root(r.categoryId)) {
      periodMinor += r.amountMinor;
    }
  }
  var windowMinor = 0;
  for (final r in windows) {
    if (!windowed.contains(r.categoryId) || !root(r.categoryId)) continue;
    windowMinor += windowShare(
      periods,
      DateRange(r.periodStart, r.periodEnd!),
      r.amountMinor,
      period,
    );
  }
  return (periodMinor: periodMinor, windowMinor: windowMinor);
}

/// Sorts lines by severity, then name.
List<BudgetLine> sortLines(Iterable<BudgetLine> lines) {
  int sev(BudgetState s) => switch (s) {
    BudgetState.over => 0,
    BudgetState.warning => 1,
    BudgetState.onTrack => 2,
  };
  return lines.toList()..sort((a, b) {
    final c = sev(a.state).compareTo(sev(b.state));
    return c != 0 ? c : a.name.toLowerCase().compareTo(b.name.toLowerCase());
  });
}
