// Exact values of the fixture library (generated by
// tool/fixtures/generate_import_fixtures.dart).

const dir = 'test/fixtures/import';

RawWorkbook read(String name) =>
    readImportFile(File('$dir/$name').readAsBytesSync(), fileName: name);

ImportAnalysis analyse(
  RawWorkbook wb, {
  ImportContext ctx = const ImportContext(),
  ImportConfig Function(ImportConfig)? adjust,
}) {
  var cfg = initialConfig(
    [wb],
    customFields: [for (final f in ctx.customFields) (f.id, f.name)],
  );
  if (adjust != null) cfg = adjust(cfg);
  return analyseImport([wb], cfg, ctx);
}

void main() {
  group('haushaltsbuch.xlsx (multi-sheet household log)', () {
    final wb = read('haushaltsbuch.xlsx');

    test('sheets, merged title, structure and mapping', () {
      expect(wb.format, SourceFormat.xlsx);
      expect(wb.sheets.map((s) => s.name), ['2023', '2024']);
      expect(wb.sheets.first.merges, contains(const MergedRange(0, 0, 0, 6)));
      final cfg = initialConfig([wb]);
      for (final s in cfg.sheets) {
        expect(s.include, isTrue);
        expect(s.headerRow, 3);
        expect(s.firstDataRow, 4);
        expect(s.amountMode, AmountMode.signed);
        expect(s.accountSource, AccountSource.fixed);
        expect(s.categorySeparator, '>');
        expect(s.targetOf(0), ColumnTarget.date);
        expect(s.targetOf(1), ColumnTarget.payee);
        expect(s.targetOf(2), ColumnTarget.note);
        expect(s.targetOf(3), ColumnTarget.category);
        expect(s.targetOf(4), ColumnTarget.amount);
        expect(s.targetOf(5), ColumnTarget.balance);
      }
      expect(cfg.sheets.map((s) => s.year), [2023, 2024]);
    });

    test('rows, subtotals, formulas by cached value, balances', () {
      final a = analyse(wb);
      final y2023 = a.sheets[0];
      final y2024 = a.sheets[1];
      expect(y2023.validRows, hasLength(110));
      expect(y2024.validRows, hasLength(56));
      expect(y2023.count(RowClass.subtotal), 12);
      // 6 × "Summe <Monat>" + "Übertrag aus 2023".
      expect(y2024.count(RowClass.subtotal), 7);
      expect(a.invalidRowCount, 0);

      final first = y2023.validRows.first;
      expect(first.date, DateTime(2023));
      expect(first.payee, 'Arbeitgeber GmbH');
      expect(first.note, 'Gehalt Januar');
      expect(first.categoryPath, ['Einkommen', 'Gehalt']);
      expect(first.amountMinor, 325000);
      expect(first.balanceMinor, 448456);
      final rewe = y2023.validRows[3];
      expect(rewe.date, DateTime(2023, 1, 5));
      expect(rewe.amountMinor, -4678);
      expect(rewe.categoryPath, ['Lebensmittel', 'Supermarkt']);
      // Kontostand is a formula: its cached value is read.
      expect(rewe.balanceMinor, 448456 - 98000 - 6500 - 4678);
      final urlaub = y2023.validRows.firstWhere(
        (r) => r.payee == 'Reisebüro Sonnenschein',
      );
      expect(urlaub.amountMinor, -124900);
      expect(urlaub.date, DateTime(2023, 8, 17));
      // A payee starting with "TOTAL" is not a sum row.
      final total = y2024.validRows.firstWhere(
        (r) => r.payee == 'TOTAL Tankstelle',
      );
      expect(total.amountMinor, -6120);

      final b = a.balances.single;
      expect(b.mismatches, isEmpty);
      expect(b.checked, 166);
      expect(b.openingMinor, 123456);
      expect(b.closingMinor, 3464494);
      expect(b.computedClosingMinor, 3464494);
    });
  });

  group('sparkonto_sh.xlsx (bank export, S/H column)', () {
    final wb = read('sparkonto_sh.xlsx');

    test(
      'preamble skipped, S/H signs, sheet-name account, info sheet excluded',
      () {
        final cfg = initialConfig([wb]);
        final spar = cfg.sheets.firstWhere((s) => s.sheetName == 'Sparkonto');
        final info = cfg.sheets.firstWhere((s) => s.sheetName == 'Info');
        expect(info.include, isFalse);
        expect(spar.headerRow, 4);
        expect(spar.amountMode, AmountMode.amountWithType);
        expect(spar.accountSource, AccountSource.sheetName);
        final a = analyse(wb);
        final rows = a.sheets.single.validRows;
        expect(rows, hasLength(20));
        expect(rows.first.date, DateTime(2023, 1, 9));
        expect(rows.first.valueDate, DateTime(2023, 1, 9));
        expect(rows.first.amountMinor, 20000);
        expect(rows.first.payee, 'Girokonto Max Mustermann');
        expect(rows.first.accountKey, 'sparkonto');
        final out = rows.firstWhere((r) => r.amountMinor! < 0);
        expect(out.date, DateTime(2024, 3, 8));
        expect(out.amountMinor, -50000);
        final zinsen = rows.firstWhere((r) => r.note == 'Zinsen');
        expect(zinsen.amountMinor, 3745);
        final b = a.balances.single;
        expect(b.ok, isTrue);
        expect(b.openingMinor, 500000);
        expect(b.closingMinor, 813745);
      },
    );
  });

  group('budget_soll_haben.xlsx (merged 2-row header, debit/credit)', () {
    final wb = read('budget_soll_haben.xlsx');
    const ctx = ImportContext(
      customFields: [ExistingField(id: 'beleg', name: 'Beleg')],
    );

    test('header, serial dates, account column, tags, broken cells', () {
      final cfg = initialConfig([wb], customFields: const [('beleg', 'Beleg')]);
      final s = cfg.sheets.single;
      expect(s.headerRow, 0);
      expect(s.headerRows, 2);
      expect(s.amountMode, AmountMode.debitCredit);
      expect(s.accountSource, AccountSource.column);
      expect(s.targetOf(4), ColumnTarget.debit);
      expect(s.targetOf(5), ColumnTarget.credit);
      expect(s.targetOf(3), ColumnTarget.subcategory);
      expect(s.targetOf(7), ColumnTarget.tags);
      expect(s.column(8)!.customFieldId, 'beleg');

      final a = analyse(wb, ctx: ctx);
      final p = a.sheets.single;
      expect(p.formats.dates[0], DateFormatKind.excelSerial);
      expect(p.formats.numbers[4], NumberFormatKind.de);
      final rows = p.validRows;
      expect(rows, hasLength(8));
      expect(rows.first.date, DateTime(2024, 1, 2));
      expect(rows.first.amountMinor, -5437);
      expect(rows.first.categoryPath, ['Lebensmittel', 'Supermarkt']);
      expect(rows.first.accountLabel, 'Girokonto');
      expect(rows.first.tags, ['familie']);
      expect(rows.first.customFields, {'beleg': 'B-001'});
      final kino = rows.firstWhere((r) => r.note == 'Kino');
      expect(kino.amountMinor, -2400); // text "24,00"
      expect(kino.tags, ['familie', 'wochenende']);
      final refund = rows.firstWhere(
        (r) => r.note == 'Erstattung Krankenkasse',
      );
      expect(refund.amountMinor, 8500);
      // "41,2O" (letter O) and 31.09. are reported with their cells.
      expect(
        [
          for (final i in p.issues)
            '${columnLetter(i.col)}${i.row + 1}:${i.kind.name}',
        ],
        ['E9:badAmount', 'A10:badDate'],
      );
      expect(p.count(RowClass.subtotal), 1);
      expect(a.accountValues.map((v) => v.label).toSet(), {
        'Girokonto',
        'Bargeld',
        'Kreditkarte',
      });
      expect(a.accountTargets['kreditkarte']!.type, AccountType.creditCard);
      expect(a.accountTargets['bargeld']!.type, AccountType.cash);
    });
  });

  group('umsaetze_win1252.csv (Windows-1252, ";", newest first)', () {
    final wb = read('umsaetze_win1252.csv');

    test('dialect, umlauts, quoted delimiters, descending balance', () {
      expect(wb.dialect!.encoding, TextEncoding.windows1252);
      expect(wb.dialect!.delimiter, ';');
      expect(wb.dialect!.lineEnding, LineEnding.crlf);
      final a = analyse(wb);
      final p = a.sheets.single;
      expect(p.config.headerRow, 3);
      expect(p.count(RowClass.title), 2);
      final rows = p.validRows;
      expect(rows, hasLength(8));
      expect(rows.first.date, DateTime(2024, 2));
      final moebel = rows.firstWhere((r) => r.payee == 'Größenwahn Möbel');
      expect(moebel.amountMinor, -123456);
      expect(moebel.note, 'Regal "Ivar"');
      final baecker = rows.firstWhere((r) => r.payee == 'Bäckerei Müller');
      expect(baecker.note, 'Brötchen; Kaffee');
      expect(baecker.amountMinor, -480);
      expect(rows.firstWhere((r) => r.payee == 'Café Süß').amountMinor, -1275);
      final b = a.balances.single;
      expect(b.descending, isTrue);
      expect(b.ok, isTrue);
      expect(b.openingMinor, 200000);
      expect(b.closingMinor, 623898);
    });
  });

  group('statement_en.csv (English, MM/dd/yyyy, 1,234.56)', () {
    final wb = read('statement_en.csv');

    test('formats, parentheses, category separator, balance', () {
      expect(wb.dialect!.hadBom, isTrue);
      expect(wb.dialect!.delimiter, ',');
      final a = analyse(wb);
      final p = a.sheets.single;
      expect(p.formats.dates[0], DateFormatKind.mdy);
      expect(p.formats.numbers[3], NumberFormatKind.en);
      final rows = p.validRows;
      expect(rows.first.date, DateTime(2024, 3));
      expect(rows.first.amountMinor, 412550);
      expect(rows.first.categoryPath, ['Income', 'Salary']);
      expect(rows[1].amountMinor, -8734);
      expect(rows[1].date, DateTime(2024, 3, 2));
      expect(rows[2].amountMinor, -145000);
      expect(rows.last.date, DateTime(2024, 3, 28));
      expect(a.balances.single.ok, isTrue);
      expect(a.balances.single.closingMinor, 343207);
    });
  });

  group('kasse_latin9.tsv (ISO-8859-15, type column)', () {
    test('euro sign, two-digit years, Einnahme/Ausgabe', () {
      final wb = read('kasse_latin9.tsv');
      expect(wb.dialect!.encoding, TextEncoding.latin9);
      expect(wb.dialect!.delimiter, '\t');
      final a = analyse(wb);
      final rows = a.sheets.single.validRows;
      expect(a.sheets.single.config.amountMode, AmountMode.amountWithType);
      expect(
        [for (final r in rows) r.amountMinor],
        [-1250, 5000, -640, 2300, -395],
      );
      expect(rows.first.date, DateTime(2024, 5, 2));
      expect(rows.last.payee, 'Bäcker');
    });
  });

  test('kalender.ods is rejected with the re-save hint', () {
    expect(
      () => read('kalender.ods'),
      throwsA(
        isA<ImportReadException>().having(
          (e) => e.error,
          'error',
          ImportReadError.ods,
        ),
      ),
    );
  });

  test('all fixtures together: transfers between Girokonto and Sparkonto', () {
    final wbs = [read('haushaltsbuch.xlsx'), read('sparkonto_sh.xlsx')];
    var cfg = initialConfig(wbs);
    cfg = cfg.copyWith(
      sheets: [
        for (final s in cfg.sheets)
          s.copyWith(
            fixedAccount: s.accountSource == AccountSource.fixed
                ? 'Girokonto'
                : null,
          ),
      ],
    );
    final a = analyseImport(wbs, cfg, const ImportContext());
    expect(a.transfers, hasLength(19));
    final pairs = [
      for (final t in a.transfers)
        (
          a.rows[t.outIndex].row.accountKey,
          a.rows[t.inIndex].row.accountKey,
          t.dayDiff,
        ),
    ];
    expect(
      pairs.where((p) => p == ('girokonto', 'sparkonto', 1)),
      hasLength(18),
    );
    expect(
      pairs.where((p) => p == ('sparkonto', 'girokonto', 0)),
      hasLength(1),
    );
  });
}
