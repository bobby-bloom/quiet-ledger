// Semantic versioning helper. `version:` in pubspec.yaml is the single source
// of truth (MAJOR.MINOR.PATCH+BUILD); see docs/VERSIONING.md.
//
//   dart run tool/version.dart                  # regenerate lib/core/app_version.dart
//   dart run tool/version.dart --check          # fail if out of sync / no changelog entry
//   dart run tool/version.dart --check --tag v1.2.3   # also require tag == version
//   dart run tool/version.dart bump <major|minor|patch|build>
//
// `bump` raises the version, always increments the build number, moves the
// CHANGELOG "Unreleased" notes into a dated section (not for `build`) and
// regenerates the Dart constants. Commit, then tag `vMAJOR.MINOR.PATCH`.
import 'dart:io';

const _pubspec = 'pubspec.yaml';
const _generated = 'lib/core/app_version.dart';
const _changelog = 'CHANGELOG.md';
const _unreleased = '## [Unreleased]';

final _versionLine = RegExp(r'^version:\s*(\S+)\s*$', multiLine: true);
final _semver = RegExp(r'^(\d+)\.(\d+)\.(\d+)\+(\d+)$');

void main(List<String> args) {
  final pubspec = File(_pubspec).readAsStringSync();
  final version = _parse(pubspec);

  if (args.isNotEmpty && args.first == 'bump') {
    if (args.length != 2) _fail('usage: bump <major|minor|patch|build>');
    final next = version.bump(args[1]);
    if (args[1] != 'build') _rollChangelog(next);
    File(
      _pubspec,
    ).writeAsStringSync(pubspec.replaceFirst(_versionLine, 'version: $next'));
    File(_generated).writeAsStringSync(_render(next));
    stdout.writeln('$version -> $next');
    stdout.writeln(
      args[1] == 'build'
          ? 'Next: commit "Build $next" (no new tag).'
          : 'Next: review $_changelog, commit "Release ${next.name}", '
                'then `git tag -a v${next.name} -m v${next.name}`.',
    );
    return;
  }

  if (args.contains('--check')) {
    final problems = <String>[];
    final file = File(_generated);
    if (!file.existsSync() || file.readAsStringSync() != _render(version)) {
      problems.add('$_generated is stale: run `dart run tool/version.dart`.');
    }
    final changelog = File(_changelog);
    if (!changelog.existsSync() ||
        !changelog.readAsStringSync().contains('## [${version.name}]')) {
      problems.add('$_changelog has no "## [${version.name}]" section.');
    }
    final tagAt = args.indexOf('--tag');
    if (tagAt >= 0) {
      final tag = tagAt + 1 < args.length ? args[tagAt + 1] : '';
      if (tag != 'v${version.name}') {
        problems.add('Tag "$tag" does not match pubspec version $version.');
      }
    }
    if (problems.isNotEmpty) _fail(problems.join('\n'));
    stdout.writeln('Version $version OK.');
    return;
  }

  File(_generated).writeAsStringSync(_render(version));
  stdout.writeln(version);
}

class _Version {
  _Version(this.major, this.minor, this.patch, this.build);

  final int major;
  final int minor;
  final int patch;
  final int build;

  String get name => '$major.$minor.$patch';

  _Version bump(String part) => switch (part) {
    'major' => _Version(major + 1, 0, 0, build + 1),
    'minor' => _Version(major, minor + 1, 0, build + 1),
    'patch' => _Version(major, minor, patch + 1, build + 1),
    'build' => _Version(major, minor, patch, build + 1),
    _ => _fail('Unknown part "$part" (major, minor, patch or build).'),
  };

  @override
  String toString() => '$name+$build';
}

_Version _parse(String pubspec) {
  final raw = _versionLine.firstMatch(pubspec)?.group(1);
  final m = raw == null ? null : _semver.firstMatch(raw);
  if (m == null) {
    _fail('$_pubspec: version must be MAJOR.MINOR.PATCH+BUILD, got "$raw".');
  }
  int at(int i) => int.parse(m.group(i)!);
  return _Version(at(1), at(2), at(3), at(4));
}

/// Moves the notes under "Unreleased" into a new dated section.
void _rollChangelog(_Version next) {
  final file = File(_changelog);
  final text = file.existsSync() ? file.readAsStringSync() : '';
  final start = text.indexOf(_unreleased);
  if (start < 0) _fail('$_changelog has no "$_unreleased" section.');
  final bodyStart = start + _unreleased.length;
  final nextSection = text.indexOf('\n## [', bodyStart);
  final bodyEnd = nextSection < 0 ? text.length : nextSection;
  final notes = text.substring(bodyStart, bodyEnd).trim();
  if (notes.isEmpty) {
    _fail('Nothing under "$_unreleased" in $_changelog: describe the release.');
  }
  final date = DateTime.now().toIso8601String().substring(0, 10);
  file.writeAsStringSync(
    '${text.substring(0, start)}$_unreleased\n\n'
    '## [${next.name}] - $date\n\n$notes\n'
    '${text.substring(bodyEnd)}',
  );
}

String _render(_Version v) =>
    '''
// GENERATED by `dart run tool/version.dart` from pubspec.yaml. Do not edit;
// change the version with `dart run tool/version.dart bump <part>`.

/// Semantic version `MAJOR.MINOR.PATCH`.
const appVersionName = '${v.name}';

/// Monotonic build number (Android versionCode, iOS CFBundleVersion).
const appBuildNumber = ${v.build};

/// `MAJOR.MINOR.PATCH+BUILD`, shown under Settings › About and written into
/// export bundles.
const appVersion = '$v';
''';

Never _fail(String message) {
  stderr.writeln(message);
  exit(1);
}
