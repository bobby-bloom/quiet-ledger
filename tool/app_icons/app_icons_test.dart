// Generates every platform's static app icon from AppMarkPainter
// (lib/app/ui/app_mark.dart), in each launcher preset's light primary.
//
//   flutter test tool/app_icons/app_icons_test.dart
//
// Rerun after changing the mark or an accent preset. Not part of the
// regular test suite. Writes:
// - Android: adaptive launcher icons per preset (mipmap-anydpi-v26,
//   colours in values/ic_launcher_colors.xml, one shared foreground that
//   doubles as the themed-icon monochrome), legacy PNGs for API < 26 and
//   the notification icon (drawable-*/ic_notification.png)
// - iOS: AppIcon (spruce) and AppIcon-<preset> asset sets, 1024 px, opaque
// - macOS: AppIcon.appiconset sizes (spruce)
// - Windows: runner/resources/app_icon.ico (spruce)
// - Web: favicon and manifest icons (spruce)
// The running app recolours the window, Dock and favicon itself
// (lib/app/app_icon).
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:personal_finance/app/app_icon/app_icon_image.dart';
import 'package:personal_finance/app/app_icon/app_icon_sync.dart';
import 'package:personal_finance/app/theme/app_theme.dart';
import 'package:personal_finance/core/settings/app_settings.dart';

const _androidRes = 'android/app/src/main/res';
const _densities = {
  'mdpi': 1.0,
  'hdpi': 1.5,
  'xhdpi': 2.0,
  'xxhdpi': 3.0,
  'xxxhdpi': 4.0,
};

void main() {
  testWidgets('generate app icons', (tester) async {
    await tester.runAsync(() async {
      final colours = {
        for (final p in launcherIconPresets)
          p: AppTheme(accent: p).light().colorScheme,
      };
      final spruce = colours[AccentScheme.spruce]!;
      await _android(colours);
      await _ios(colours);
      await _macos(spruce);
      await _windows(spruce);
      await _web(spruce);
    });
  });
}

String _launcherName(AccentScheme p) =>
    p == AccentScheme.spruce ? 'ic_launcher' : 'ic_launcher_${p.name}';

String _hex(Color c) =>
    '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

Future<void> _android(Map<AccentScheme, ColorScheme> colours) async {
  final xml = StringBuffer(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- Generated by tool/app_icons; launcher icon backgrounds. -->\n'
    '<resources>\n',
  );
  for (final MapEntry(key: p, value: c) in colours.entries) {
    xml.writeln(
      '    <color name="${_launcherName(p)}_background">'
      '${_hex(c.primary)}</color>',
    );
    _write(
      '$_androidRes/mipmap-anydpi-v26/${_launcherName(p)}.xml',
      utf8.encode(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/app_icons. -->\n'
        '<adaptive-icon '
        'xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/'
        '${_launcherName(p)}_background"/>\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>\n'
        '</adaptive-icon>\n',
      ),
    );
    for (final MapEntry(key: d, value: scale) in _densities.entries) {
      // API < 26: a full icon at 48 dp.
      _write(
        '$_androidRes/mipmap-$d/${_launcherName(p)}.png',
        await renderAppIconPng(
          (48 * scale).round(),
          background: c.primary,
          foreground: c.onPrimary,
        ),
      );
    }
  }
  xml.writeln('</resources>');
  _write('$_androidRes/values/ic_launcher_colors.xml', utf8.encode('$xml'));

  for (final MapEntry(key: d, value: scale) in _densities.entries) {
    // Adaptive foreground: 108 dp canvas, the mark inside the 66 dp circle.
    _write(
      '$_androidRes/mipmap-$d/ic_launcher_foreground.png',
      await renderAppIconPng(
        (108 * scale).round(),
        background: Colors.transparent,
        foreground: Colors.white,
        shape: AppIconShape.markOnly,
      ),
    );
    // Notification: 24 dp, the mark filling most of it.
    _write(
      '$_androidRes/drawable-$d/ic_notification.png',
      await renderAppIconPng(
        (24 * scale).round(),
        background: Colors.transparent,
        foreground: Colors.white,
        shape: AppIconShape.markOnly,
        markScale: 1.75,
      ),
    );
  }
}

Future<void> _ios(Map<AccentScheme, ColorScheme> colours) async {
  const assets = 'ios/Runner/Assets.xcassets';
  final primary = Directory('$assets/AppIcon.appiconset');
  if (primary.existsSync()) primary.deleteSync(recursive: true);
  for (final MapEntry(key: p, value: c) in colours.entries) {
    final name = p == AccentScheme.spruce ? 'AppIcon' : 'AppIcon-${p.name}';
    const file = 'Icon-1024.png';
    final image = await renderAppIcon(
      1024,
      background: c.primary,
      foreground: c.onPrimary,
      shape: AppIconShape.square,
    );
    final rgba = await image.toByteData();
    image.dispose();
    _write('$assets/$name.appiconset/$file', _opaquePng(1024, rgba!));
    _write(
      '$assets/$name.appiconset/Contents.json',
      utf8.encode(
        const JsonEncoder.withIndent('  ').convert({
          'images': [
            {
              'filename': file,
              'idiom': 'universal',
              'platform': 'ios',
              'size': '1024x1024',
            },
          ],
          'info': {'author': 'xcode', 'version': 1},
        }),
      ),
    );
  }
}

Future<void> _macos(ColorScheme c) async {
  const dir = 'macos/Runner/Assets.xcassets/AppIcon.appiconset';
  for (final size in const [16, 32, 64, 128, 256, 512, 1024]) {
    _write(
      '$dir/app_icon_$size.png',
      await renderAppIconPng(
        size,
        background: c.primary,
        foreground: c.onPrimary,
        shape: AppIconShape.macos,
      ),
    );
  }
}

Future<void> _windows(ColorScheme c) async {
  _write(
    'windows/runner/resources/app_icon.ico',
    await renderAppIconIco(background: c.primary, foreground: c.onPrimary),
  );
}

Future<void> _web(ColorScheme c) async {
  Future<Uint8List> icon(int size, AppIconShape shape) => renderAppIconPng(
    size,
    background: c.primary,
    foreground: c.onPrimary,
    shape: shape,
  );
  _write('web/favicon.png', await icon(32, AppIconShape.rounded));
  for (final size in const [192, 512]) {
    _write('web/icons/Icon-$size.png', await icon(size, AppIconShape.rounded));
    _write(
      'web/icons/Icon-maskable-$size.png',
      await icon(size, AppIconShape.square),
    );
  }
}

void _write(String path, List<int> bytes) {
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsBytesSync(bytes);
}

/// RGB PNG (no alpha channel, as the App Store requires) from opaque RGBA.
Uint8List _opaquePng(int size, ByteData rgba) {
  final raw = BytesBuilder();
  for (var y = 0; y < size; y++) {
    raw.addByte(0); // filter: none
    for (var x = 0; x < size; x++) {
      final p = (y * size + x) * 4;
      raw
        ..addByte(rgba.getUint8(p))
        ..addByte(rgba.getUint8(p + 1))
        ..addByte(rgba.getUint8(p + 2));
    }
  }
  final header = ByteData(13)
    ..setUint32(0, size)
    ..setUint32(4, size)
    ..setUint8(8, 8) // bit depth
    ..setUint8(9, 2); // colour type: RGB
  final out = BytesBuilder()
    ..add(const [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
  void chunk(String type, List<int> data) {
    final typed = [...ascii.encode(type), ...data];
    out
      ..add((ByteData(4)..setUint32(0, data.length)).buffer.asUint8List())
      ..add(typed)
      ..add((ByteData(4)..setUint32(0, _crc32(typed))).buffer.asUint8List());
  }

  chunk('IHDR', header.buffer.asUint8List());
  chunk('IDAT', ZLibEncoder(level: 9).convert(raw.takeBytes()));
  chunk('IEND', const []);
  return out.takeBytes();
}

final _crcTable = List<int>.generate(256, (n) {
  var c = n;
  for (var k = 0; k < 8; k++) {
    c = (c & 1) != 0 ? 0xEDB88320 ^ (c >> 1) : c >> 1;
  }
  return c;
});

int _crc32(List<int> bytes) {
  var c = 0xFFFFFFFF;
  for (final b in bytes) {
    c = _crcTable[(c ^ b) & 0xFF] ^ (c >> 8);
  }
  return c ^ 0xFFFFFFFF;
}
